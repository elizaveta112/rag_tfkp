def main():
    questions, gold = [], []
    for i, (category, question, options, ids, pages, source, rationale) in enumerate(DATA, 1):
        q = {'id': f'own_{i:03d}', 'question': question,
             'options': [{'id': chr(65+j), 'text': t} for j, t in enumerate(options)]}
        validate_question(q)
        g = {'id': q['id'], 'category': category, 'answer_ids': ids,
             'abstain': not ids, 'rationale': rationale, 'source_pages': pages,
             'source_description': source, 'citation_sets': [],
             'gold_status': 'pending_original_block_ids'}
        if not ids:
            g['missing_information'] = 'Не задано f(0).' if i == 7 else 'Не задано f′(0), или c_1.'
        questions.append(q)
        gold.append(g)
    write_jsonl(project_path(ROOT, 'own_questions.jsonl'), questions)
    write_jsonl(project_path(ROOT, 'own_gold.jsonl'), gold)


if __name__ == '__main__':
    main()
